func TestExportProducesDeterministicHeaderAndDigestReceipt(t *testing.T) {
	directory := t.TempDir()
	sourcePath := filepath.Join(directory, "settings.pipe")
	outputPath := filepath.Join(directory, "PipeViewDocument.hpp")
	text := []byte(`view Settings { Label(id:"title",text:"Settings 🏍"); }`)
	if err := os.WriteFile(sourcePath, text, 0600); err != nil {
		t.Fatal(err)
	}
	arguments := []string{"--source", sourcePath, "--output", outputPath}
	if err := run(arguments); err != nil {
		t.Fatal(err)
	}
	generated, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(generated), "namespace compiled_ui") || !strings.Contains(string(generated), "inline std::string view()") {
		t.Fatalf("missing header entrypoint: %s", generated)
	}
	receiptBytes, err := os.ReadFile(outputPath + ".json")
	if err != nil {
		t.Fatal(err)
	}
	var receipt metadata
	if err := json.Unmarshal(receiptBytes, &receipt); err != nil {
		t.Fatal(err)
	}
	if receipt.Contract != "pipelang.pipeview.export.v1" || receipt.SourceContract != "pipelang.pipeview.source.v1" || receipt.Adapter == "" || receipt.SourceSHA256 != digest(text) || receipt.GeneratedSHA256 != digest(generated) || len(receipt.CompilerExecutableSHA256) != 64 || receipt.LexerExecutableSHA256 != "" {
		t.Fatalf("incorrect provenance receipt: %#v", receipt)
	}
	if err := run(arguments); err != nil {
		t.Fatal(err)
	}
	repeated, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(repeated) != string(generated) {
		t.Fatal("repeated source export changed generated bytes")
	}
	original, err := os.ReadFile(sourcePath)
	if err != nil || string(original) != string(text) {
		t.Fatalf("source changed during export: %q, %v", original, err)
	}
}

func TestHeaderEscapesEveryTransportByte(t *testing.T) {
	transport := []byte("\x00\n\"\\af🏍\xff09")
	generated := string(header(transport))
	var decoded strings.Builder
	for _, line := range strings.Split(generated, "\n") {
		literal := strings.TrimSpace(line)
		if !strings.HasPrefix(literal, `"`) {
			continue
		}
		value, err := strconv.Unquote(literal)
		if err != nil {
			t.Fatalf("invalid byte literal %q: %v", literal, err)
		}
		decoded.WriteString(value)
	}
	if decoded.String() != string(transport) || !strings.Contains(generated, ", "+strconv.Itoa(len(transport))+");") {
		t.Fatalf("transport byte identity lost: %q, header=%s", decoded.String(), generated)
	}
}

func TestExportRefusalsPreserveExistingOutputs(t *testing.T) {
	cases := []struct {
		name      string
		text      string
		arguments func(string, string) []string
	}{
		{"semantic error", `view X { Button(id:"x",clicked:missing); }`, nil},
		{"syntax error", `view X { Label(id:"x") }`, nil},
		{"empty source", "", nil},
		{"large source", strings.Repeat(" ", 65537), nil},
		{"relative source", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", "relative.pipe", "--output", output}
		}},
		{"relative output", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", source, "--output", "relative.hpp"}
		}},
		{"positional argument", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", source, "--output", output, "extra"}
		}},
		{"unpaired lexer", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", source, "--output", output, "--cpp-lexer", "/missing/lexer"}
		}},
		{"unpaired lexer hash", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", source, "--output", output, "--cpp-lexer-sha256", strings.Repeat("a", 64)}
		}},
		{"invalid selected lexer", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", source, "--output", output, "--cpp-lexer", "/missing/pipeview-lexer", "--cpp-lexer-sha256", strings.Repeat("a", 64)}
		}},
		{"source equals output", `view X { Label(id:"x"); }`, func(source, output string) []string {
			return []string{"--source", source, "--output", source}
		}},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			directory := t.TempDir()
			sourcePath := filepath.Join(directory, "settings.pipe")
			outputPath := filepath.Join(directory, "PipeViewDocument.hpp")
			for path, data := range map[string]string{sourcePath: test.text, outputPath: "existing-header", outputPath + ".json": "existing-receipt"} {
				if err := os.WriteFile(path, []byte(data), 0600); err != nil {
					t.Fatal(err)
				}
			}
			arguments := []string{"--source", sourcePath, "--output", outputPath}
			if test.arguments != nil {
				arguments = test.arguments(sourcePath, outputPath)
			}
			if err := run(arguments); err == nil {
				t.Fatal("invalid export was accepted")
			}
			for path, expected := range map[string]string{sourcePath: test.text, outputPath: "existing-header", outputPath + ".json": "existing-receipt"} {
				actual, err := os.ReadFile(path)
				if err != nil || string(actual) != expected {
					t.Fatalf("refusal changed %s: %q, %v", path, actual, err)
				}
			}
		})
	}
}

func TestExportRefusesNonregularDestinationsBeforeWriting(t *testing.T) {
	for _, metadataDestination := range []bool{false, true} {
		directory := t.TempDir()
		sourcePath := filepath.Join(directory, "settings.pipe")
		outputPath := filepath.Join(directory, "PipeViewDocument.hpp")
		if err := os.WriteFile(sourcePath, []byte(`view X { Label(id:"x"); }`), 0600); err != nil {
			t.Fatal(err)
		}
		blockedPath := outputPath
		if metadataDestination {
			blockedPath += ".json"
			if err := os.WriteFile(outputPath, []byte("existing-header"), 0600); err != nil {
				t.Fatal(err)
			}
		}
		if err := os.Mkdir(blockedPath, 0700); err != nil {
			t.Fatal(err)
		}
		if err := run([]string{"--source", sourcePath, "--output", outputPath}); err == nil {
			t.Fatal("nonregular destination was accepted")
		}
		if metadataDestination {
			actual, err := os.ReadFile(outputPath)
			if err != nil || string(actual) != "existing-header" {
				t.Fatalf("metadata preflight failed to preserve header: %q, %v", actual, err)
			}
		}
	}
}

func TestExportRefusesSymlinkDestinations(t *testing.T) {
	for _, suffix := range []string{"", ".json"} {
		directory := t.TempDir()
		sourcePath := filepath.Join(directory, "settings.pipe")
		outputPath := filepath.Join(directory, "PipeViewDocument.hpp")
		targetPath := filepath.Join(directory, "preserved.txt")
		if err := os.WriteFile(sourcePath, []byte(`view X { Label(id:"x"); }`), 0600); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(targetPath, []byte("preserved-target"), 0600); err != nil {
			t.Fatal(err)
		}
		if suffix == ".json" {
			if err := os.WriteFile(outputPath, []byte("existing-header"), 0600); err != nil {
				t.Fatal(err)
			}
		}
		if err := os.Symlink(targetPath, outputPath+suffix); err != nil {
			t.Fatal(err)
		}
		if err := run([]string{"--source", sourcePath, "--output", outputPath}); err == nil {
			t.Fatal("symlink destination was accepted")
		}
		actual, err := os.ReadFile(targetPath)
		if err != nil || string(actual) != "preserved-target" {
			t.Fatalf("symlink target changed: %q, %v", actual, err)
		}
		info, err := os.Lstat(outputPath + suffix)
		if err != nil || info.Mode()&os.ModeSymlink == 0 {
			t.Fatalf("destination symlink changed: %v", err)
		}
	}
}

func TestExportRefusesSourceAtMetadataPath(t *testing.T) {
	directory := t.TempDir()
	outputPath := filepath.Join(directory, "PipeViewDocument.hpp")
	sourcePath := outputPath + ".json"
	text := `view X { Label(id:"x"); }`
	if err := os.WriteFile(sourcePath, []byte(text), 0600); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"--source", sourcePath, "--output", outputPath}); err == nil {
		t.Fatal("source at metadata path was accepted")
	}
	actual, err := os.ReadFile(sourcePath)
	if err != nil || string(actual) != text {
		t.Fatalf("source changed: %q, %v", actual, err)
	}
	if _, err := os.Stat(outputPath); !os.IsNotExist(err) {
		t.Fatalf("refused export created output: %v", err)
	}
}

func TestInvalidSourceCreatesNoArtifacts(t *testing.T) {
	directory := t.TempDir()
	sourcePath := filepath.Join(directory, "settings.pipe")
	outputPath := filepath.Join(directory, "PipeViewDocument.hpp")
	if err := os.WriteFile(sourcePath, []byte(`view X { state a:bool="wrong"; Label(id:"x"); }`), 0600); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"--source", sourcePath, "--output", outputPath}); err == nil {
		t.Fatal("invalid source was accepted")
	}
	for _, path := range []string{outputPath, outputPath + ".json"} {
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Fatalf("refused export created %s: %v", path, err)
		}
	}
}
