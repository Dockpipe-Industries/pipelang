package cppbackend

import (
	_ "embed"
	"fmt"
	"strings"

	"github.com/Dockpipe-Industries/pipelang/src/lib/pipelang/coreir"
)

//go:embed float64_runtime.hpp
var float64Support string

type float64Generator struct {
	strings.Builder
	indent      int
	temporaries int
}

func (generator *float64Generator) line(text string) {
	generator.WriteString(strings.Repeat("    ", generator.indent))
	generator.WriteString(text)
	generator.WriteByte('\n')
}

func (generator *float64Generator) temporary(typ, expression string) string {
	generator.temporaries++
	variable := fmt.Sprintf("v%d", generator.temporaries)
	generator.line(typ + " " + variable + " = " + expression + ";")
	return variable
}

func float64Symbol(function float64Function) string {
	return name("fn_", function.PackageID+"\x00"+function.Path)
}

func float64Bindings(program coreir.Program, functions []float64Function) []Binding {
	identities := make(map[string]coreir.SemanticIdentity, len(program.Functions))
	for _, function := range program.Functions {
		identities[key(function.Identity)] = function.Identity
	}
	bindings := make([]Binding, 0, len(functions))
	for _, function := range functions {
		bindings = append(bindings, Binding{Identity: identities[function.PackageID+"\x00"+function.Path], Name: float64Symbol(function)})
	}
	return bindings
}

func generateFloat64(request float64Request, program coreir.Program) Generated {
	generator := float64Generator{}
	generator.WriteString("// Generated by " + request.Profile + ". C++17 / IEEE binary64 comparisons.\n")
	generator.WriteString(float64Support)
	generator.WriteString("\nnamespace pipelang {\n")
	for _, function := range request.Functions {
		parameters := make([]string, 0, len(function.Parameters))
		for index, tag := range function.Parameters {
			typ := "bool"
			if tag == "float64" {
				typ = "double"
			}
			parameters = append(parameters, fmt.Sprintf("%s p%d", typ, index))
		}
		returnType := "bool"
		if function.ReturnType == "float64" {
			returnType = "double"
		}
		generator.line("inline " + returnType + " " + float64Symbol(function) + "(" + strings.Join(parameters, ", ") + ")")
		generator.line("{")
		generator.indent++
		result := generator.expression(function.Body)
		generator.line("return " + result + ";")
		generator.indent--
		generator.line("}")
	}
	generator.line("}")
	return Generated{Source: []byte(generator.String()), Functions: float64Bindings(program, request.Functions)}
}

func (generator *float64Generator) expression(expression float64Expression) string {
	switch expression.Kind {
	case string(coreir.ExprReference):
		return fmt.Sprintf("p%d", *expression.Parameter)
	case string(coreir.ExprLiteral):
		if expression.Type == "float64" {
			return generator.temporary("const double", "float64_comparison_detail::from_bits(UINT64_C(0x"+expression.Float64Bits+"))")
		}
		return generator.temporary("const bool", fmt.Sprint(*expression.Boolean))
	case string(coreir.ExprConditional):
		condition := generator.expression(expression.Operands[0])
		resultType := "bool"
		if expression.Type == "float64" {
			resultType = "double"
		}
		generator.temporaries++
		result := fmt.Sprintf("v%d", generator.temporaries)
		generator.line(resultType + " " + result + ";")
		generator.line("if (" + condition + ") {")
		generator.indent++
		whenTrue := generator.expression(expression.Operands[1])
		generator.line(result + " = " + whenTrue + ";")
		generator.indent--
		generator.line("} else {")
		generator.indent++
		whenFalse := generator.expression(expression.Operands[2])
		generator.line(result + " = " + whenFalse + ";")
		generator.indent--
		generator.line("}")
		return result
	case string(coreir.ExprUnary):
		operand := generator.expression(expression.Operands[0])
		return generator.temporary("const bool", "!"+operand)
	case string(coreir.ExprBinary):
		left := generator.expression(expression.Operands[0])
		if expression.Operator == string(coreir.OperatorAnd) || expression.Operator == string(coreir.OperatorOr) {
			result := generator.temporary("bool", left)
			condition := result
			if expression.Operator == string(coreir.OperatorOr) {
				condition = "!" + condition
			}
			generator.line("if (" + condition + ") {")
			generator.indent++
			right := generator.expression(expression.Operands[1])
			generator.line(result + " = " + right + ";")
			generator.indent--
			generator.line("}")
			return result
		}
		right := generator.expression(expression.Operands[1])
		operators := map[string]string{"equal": "==", "not_equal": "!=", "less_than": "<", "less_or_equal": "<=", "greater_than": ">", "greater_or_equal": ">="}
		return generator.temporary("const bool", left+" "+operators[expression.Operator]+" "+right)
	default:
		panic("unadmitted float64 expression reached emitter")
	}
}
