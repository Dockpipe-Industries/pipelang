std::string emit(const View &view)
{
    std::vector<const Node *> nodes;
    flatten(view.root, nodes);
    const std::string adapter = view.name + "Adapter";
    std::ostringstream output;
    output << "// Generated by pipelang.native-model-view.v1. Do not edit.\n#pragma once\n"
        << "#include " << quote(view.modelHeader) << "\n"
        << "#include <forgepipe/ui/Session.h>\n#include <pipelang/model/runtime.hpp>\n"
        << "#include <functional>\n#include <memory>\n#include <optional>\n#include <thread>\n"
        << "#include <utility>\n#include <vector>\n\nnamespace " << view.nameSpace << " {\n"
        << "class " << adapter << " final {\npublic:\n"
        << "    using Model = " << view.model << ";\n"
        << "    using InvocationResult = pipelang::model::InvocationResult;\n"
        << "    struct ControlInspection {\n        std::string id;\n        forgepipe::ui::ControlType role;\n"
        << "        std::optional<forgepipe::ui::Value> value;\n        bool enabled = true;\n"
        << "        std::string action;\n        std::string binding;\n        std::string valueType;\n        bool redacted = false;\n    };\n"
        << "    struct Projection {\n        forgepipe::ui::State state;\n        forgepipe::ui::EnabledProperties enabled;\n"
        << "        std::vector<ControlInspection> controls;\n    };\n"
        << "    struct ActionReport {\n        InvocationResult outcome = InvocationResult::Success();\n"
        << "        InvocationResult projection = InvocationResult::Success();\n        bool pending = false;\n"
        << "        std::string control;\n        std::string action;\n    };\n"
        << "    struct PollReport {\n        std::size_t delivered = 0;\n        std::vector<ActionReport> completed;\n"
        << "        InvocationResult projection = InvocationResult::Success();\n    };\n\n"
        << "    // The model must outlive this owner-thread adapter.\n"
        << "    static std::unique_ptr<" << adapter << "> create(Model &model, std::string &error, std::size_t capacity = 32)\n    {\n"
        << "        if (capacity == 0 || capacity > 32) {\n            error = \"view task capacity must be within 1..32\";\n            return {};\n        }\n"
        << "        try {\n            auto adapter = std::unique_ptr<" << adapter << ">(new " << adapter << "(model, capacity));\n"
        << "            auto projection = adapter->evaluateProjection();\n"
        << "            auto session = forgepipe::ui::Session::create(makeDocument(), projection.state, error);\n"
        << "            if (!session || !session->applyProjection(projection.state, projection.enabled, error))\n                return {};\n"
        << "            adapter->session_ = std::move(session);\n            adapter->projection_ = std::move(projection);\n"
        << "            error.clear();\n            return adapter;\n        } catch (const std::exception &failure) {\n"
        << "            error = failure.what();\n            return {};\n        }\n    }\n"
        << "    ~" << adapter << "()\n    {\n        for (const auto &pending : pending_)\n            pending.cancel();\n    }\n"
        << "    " << adapter << "(const " << adapter << " &) = delete;\n"
        << "    " << adapter << " &operator=(const " << adapter << " &) = delete;\n"
        << "    std::shared_ptr<forgepipe::ui::Session> session() const\n    {\n        requireOwner();\n        return session_;\n    }\n"
        << "    // Raw rendering state can include sensitive values. Use inspection() for sanitized metadata.\n"
        << "    const Projection &projection() const\n    {\n        requireOwner();\n        return projection_;\n    }\n"
        << "    const std::vector<ControlInspection> &inspection() const\n    {\n        requireOwner();\n        return projection_.controls;\n    }\n"
        << "    std::size_t pending() const\n    {\n        requireOwner();\n        return pending_.size();\n    }\n"
        << "    void cancelPending()\n    {\n        requireOwner();\n        for (const auto &pending : pending_)\n            pending.cancel();\n    }\n"
        << "    InvocationResult project()\n    {\n        requireOwner();\n        try {\n"
        << "            auto candidate = evaluateProjection();\n            std::string error;\n"
        << "            if (!session_->applyProjection(candidate.state, candidate.enabled, error))\n                return InvocationResult::Failure(error);\n"
        << "            projection_ = std::move(candidate);\n            return InvocationResult::Success();\n"
        << "        } catch (const std::exception &failure) {\n            return InvocationResult::Failure(failure.what());\n        }\n    }\n"
        << "    ActionReport dispatch(const forgepipe::ui::Event &event)\n    {\n        requireOwner();\n"
        << "        ActionReport report;\n        report.control = event.control;\n        report.action = event.action;\n"
        << "        try {\n";
    bool first = true;
    for (const auto *node : nodes) {
        if (node->action.method.empty())
            continue;
        output << "            " << (first ? "if" : "else if") << " (event.control == " << quote(node->identity) << ") {\n"
            << "                const forgepipe::ui::ActionBinding binding{" << quote(node->identity) << ", "
            << quote(node->action.method) << ", " << quote(node->value.expression.empty() ? "" : node->value.identity)
            << ", forgepipe::ui::ValueKind::" << valueKind(node->action.payloadType)
            << ", forgepipe::ui::EventType::" << (node->kind == "Button" ? "Activated" : "ValueChanged") << "};\n"
            << "                const auto admitted = forgepipe::ui::admitActionEvent(*session_, binding, event);\n"
            << "                if (admitted.status == forgepipe::ui::InvocationStatus::Failure) {\n"
            << "                    report.outcome = InvocationResult::Failure(admitted.error);\n"
            << "                } else if (admitted.status == forgepipe::ui::InvocationStatus::Cancelled) {\n"
            << "                    report.outcome = InvocationResult::Cancelled();\n                } else {\n";
        if (node->action.asynchronous) {
            output << "                    if (pending_.size() >= capacity_) {\n"
                << "                        report.outcome = InvocationResult::Failure(\"view task capacity exceeded\");\n"
                << "                    } else {\n                        pipelang::model::CancellationSource cancellation;\n"
                << "                        auto task = " << call(*node) << ";\n"
                << "                        if (task.completed()) {\n                            report.outcome = outcome(task.result());\n"
                << "                        } else {\n                            try {\n                                Pending pending;\n"
                << "                                pending.control = event.control;\n                                pending.action = event.action;\n"
                << "                                pending.completed = [task] {\n                                    return task.completed();\n                                };\n"
                << "                                pending.result = [task] {\n                                    return outcome(task.result());\n                                };\n"
                << "                                pending.cancel = [task, cancellation] {\n                                    cancellation.cancel();\n                                    task.cancel();\n                                };\n"
                << "                                pending_.push_back(std::move(pending));\n                                report.pending = true;\n"
                << "                            } catch (...) {\n                                cancellation.cancel();\n                                task.cancel();\n                                throw;\n                            }\n"
                << "                        }\n                    }\n";
        } else {
            if (node->action.cancellation)
                output << "                    pipelang::model::CancellationSource cancellation;\n";
            output << "                    report.outcome = outcome(" << call(*node) << ");\n";
        }
        output << "                }\n            }\n";
        first = false;
    }
    if (first)
        output << "            report.outcome = InvocationResult::Failure(\"unknown view event control\");\n";
    else
        output << "            else {\n                report.outcome = InvocationResult::Failure(\"unknown view event control\");\n            }\n";
    output << "        } catch (const std::exception &failure) {\n            report.outcome = InvocationResult::Failure(failure.what());\n        }\n"
        << "        report.projection = project();\n        return report;\n    }\n"
        << "    std::vector<ActionReport> dispatch(const std::vector<forgepipe::ui::Event> &events)\n    {\n"
        << "        requireOwner();\n        if (events.empty()) {\n            ActionReport report;\n            report.projection = project();\n            return {report};\n        }\n"
        << "        if (events.size() > forgepipe::ui::Session::maximumPendingEvents) {\n"
        << "            ActionReport report;\n            report.outcome = InvocationResult::Failure(\"view event batch capacity exceeded\");\n"
        << "            return {report};\n        }\n        std::vector<ActionReport> reports;\n        reports.reserve(events.size());\n"
        << "        for (const auto &event : events)\n            reports.push_back(dispatch(event));\n        return reports;\n    }\n"
        << "    PollReport poll()\n    {\n        requireOwner();\n        PollReport report;\n"
        << "        try {\n            report.delivered = model_.poll();\n            auto entry = pending_.begin();\n"
        << "            while (entry != pending_.end()) {\n                if (!entry->completed()) {\n                    ++entry;\n                    continue;\n                }\n"
        << "                ActionReport completed;\n                completed.control = entry->control;\n                completed.action = entry->action;\n"
        << "                completed.outcome = entry->result();\n                report.completed.push_back(std::move(completed));\n"
        << "                entry = pending_.erase(entry);\n            }\n        } catch (const std::exception &failure) {\n"
        << "            ActionReport completed;\n            completed.outcome = InvocationResult::Failure(failure.what());\n"
        << "            report.completed.push_back(std::move(completed));\n        }\n        report.projection = project();\n"
        << "        for (auto &completed : report.completed)\n            completed.projection = report.projection;\n        return report;\n    }\n"
        << "private:\n    struct Pending {\n        std::string control;\n        std::string action;\n"
        << "        std::function<bool()> completed;\n        std::function<InvocationResult()> result;\n"
        << "        std::function<void()> cancel;\n    };\n"
        << "    " << adapter << "(Model &model, std::size_t capacity) : model_(model), capacity_(capacity)\n"
        << "    {\n        pending_.reserve(capacity);\n    }\n"
        << "    void requireOwner() const\n    {\n        if (owner_ != std::this_thread::get_id())\n"
        << "            throw pipelang::model::ExecutionFailure(\"view accessed from a different owner thread\");\n    }\n"
        << "    template<class T>\n    static InvocationResult outcome(const T &result)\n    {\n"
        << "        if (result.is_success())\n            return InvocationResult::Success();\n"
        << "        if (result.is_cancelled())\n            return InvocationResult::Cancelled(result.error());\n"
        << "        return InvocationResult::Failure(result.error());\n    }\n"
        << "    static forgepipe::ui::Document makeDocument()\n    {\n        forgepipe::ui::Document document;\n";
    std::size_t next = 0;
    documentNode(view.root, output, next);
    output << "        document.root = std::move(node0);\n        return document;\n    }\n"
        << "    Projection evaluateProjection() const\n    {\n        const auto snapshot = model_.snapshot();\n"
        << "        (void)snapshot;\n        Projection result;\n";
    std::size_t index = 0;
    for (const auto *node : nodes) {
        output << "        const bool enabled" << index << " = " << node->enabledExpression << ";\n"
            << "        result.enabled.emplace(" << quote(node->identity) << ", enabled" << index << ");\n";
        if (!node->value.expression.empty())
            output << "        result.state.emplace(" << quote(node->value.identity) << ", " << node->value.expression << ");\n";
        output << "        result.controls.push_back({" << quote(node->identity) << ", forgepipe::ui::ControlType::" << node->kind << ", ";
        if (node->value.expression.empty() || node->sensitive)
            output << "std::nullopt";
        else
            output << "result.state.at(" << quote(node->value.identity) << ")";
        output << ", enabled" << index << ", " << quote(node->action.method) << ", " << quote(node->value.identity) << ", " << quote(node->value.type) << ", " << (node->sensitive ? "true" : "false") << "});\n";
        ++index;
    }
    output << "        return result;\n    }\n    Model &model_;\n"
        << "    std::shared_ptr<forgepipe::ui::Session> session_;\n    Projection projection_;\n"
        << "    std::vector<Pending> pending_;\n    std::size_t capacity_;\n"
        << "    std::thread::id owner_ = std::this_thread::get_id();\n};\n}\n";
    return output.str();
}
