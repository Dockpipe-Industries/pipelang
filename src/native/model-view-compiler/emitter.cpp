std::string quote(const std::string &value)
{
    std::string result = "\"";
    for (unsigned char character : value) {
        if (character == '"' || character == '\\') {
            result += '\\';
            result += static_cast<char>(character);
        } else if (character >= 32 && character < 127) {
            result += static_cast<char>(character);
        } else {
            result += '\\';
            result += char('0' + ((character >> 6) & 7));
            result += char('0' + ((character >> 3) & 7));
            result += char('0' + (character & 7));
        }
    }
    return result + '"';
}
void flatten(const Node &node, std::vector<const Node *> &nodes)
{
    nodes.push_back(&node);
    for (const auto &child : node.children)
        flatten(child, nodes);
}
std::string cppType(const std::string &type)
{
    if (type == "string")
        return "std::string";
    if (type == "int")
        return "std::int64_t";
    return "bool";
}
std::string valueKind(const std::string &type)
{
    if (type == "string")
        return "Text";
    if (type == "int")
        return "Integer";
    if (type == "bool")
        return "Boolean";
    return "None";
}
std::string call(const Node &node)
{
    std::string result = "model_." + node.action.method + '(';
    for (std::size_t index = 0; index < node.action.cancellationParameters.size(); ++index) {
        if (index)
            result += ", ";
        if (node.action.cancellationParameters[index])
            result += "cancellation.token()";
        else
            result += "std::get<" + cppType(node.action.payloadType) + ">(admitted.value)";
    }
    return result + ')';
}
std::size_t documentNode(const Node &node, std::ostringstream &output, std::size_t &next)
{
    const auto index = next++;
    const auto variable = "node" + std::to_string(index);
    output << "        forgepipe::ui::Node " << variable << ";\n"
        << "        " << variable << ".id = " << quote(node.identity) << ";\n"
        << "        " << variable << ".type = forgepipe::ui::ControlType::" << node.kind << ";\n";
    if (!node.label.empty())
        output << "        " << variable << ".text = " << quote(node.label) << ";\n";
    if (!node.value.expression.empty())
        output << "        " << variable << ".binding = " << quote(node.value.identity) << ";\n";
    if (!node.action.method.empty())
        output << "        " << variable << ".action = " << quote(node.action.method) << ";\n";
    if (node.width)
        output << "        " << variable << ".width = " << node.width << ";\n";
    if (node.height)
        output << "        " << variable << ".height = " << node.height << ";\n";
    for (const auto &child : node.children) {
        const auto childIndex = documentNode(child, output, next);
        output << "        " << variable << ".children.push_back(std::move(node" << childIndex << "));\n";
    }
    return index;
}
