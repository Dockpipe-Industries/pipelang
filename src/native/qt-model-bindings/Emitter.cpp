#include "BindingModel.hpp"
#include <sstream>
#include <stdexcept>

namespace pipelang::qt_bindings {
namespace {
std::string qtType(const std::string& type) {
    if (type == "bool")
        return "bool";
    return type == "string" ? "QString" : "QStringList";
}
}
std::string emit(const BindingModel& model, const std::string& nameSpace, const std::string& adapter) {
    if (!identifier(nameSpace) || !identifier(adapter))
        throw std::runtime_error("unsafe Qt adapter identity");
    for (const auto& action : model.actions) {
        if (action.name == adapter)
            throw std::runtime_error("Qt action collides with adapter constructor");
    }
    std::ostringstream out;
    out << "// Generated by pipelang.qt-model-bindings.v1.\n#pragma once\n"
        << "#include \"Model.hpp\"\n#include <pipelang/qt/Conversions.hpp>\n"
        << "#include <QThread>\n#include <QScopedValueRollback>\n#include <memory>\n"
        << "namespace " << nameSpace << " {\nclass " << adapter << " final : public QObject {\n    Q_OBJECT\n"
        << "    Q_PROPERTY(int successOutcome READ successOutcome CONSTANT)\n"
        << "    Q_PROPERTY(int cancelledOutcome READ cancelledOutcome CONSTANT)\n"
        << "    Q_PROPERTY(int failureOutcome READ failureOutcome CONSTANT)\n"
        << "    Q_PROPERTY(pipelang::qt::InvocationOutcome projectionStatus READ projectionStatus NOTIFY projectionChanged)\n";
    for (const auto& property : model.properties)
        out << "    Q_PROPERTY(" << qtType(property.type) << ' ' << property.name << " READ pl_get_" << property.name << " NOTIFY projectionChanged)\n";
    out << "public:\n    using Model = ::" << model.modelNamespace << "::" << model.nativeModel << ";\n"
        << "    explicit " << adapter << "(std::unique_ptr<Model> model, QObject* parent = nullptr)\n"
        << "        : QObject(parent), pl_model_(std::move(model)), pl_owner_(QThread::currentThread()) {\n"
        << "        if (!pl_model_) throw pipelang::model::ExecutionFailure(\"qt.null_model\");\n"
        << "        qRegisterMetaType<pipelang::qt::InvocationOutcome>();\n"
        << "        qRegisterMetaType<pipelang::qt::ActionReport>();\n        (void)pl_project();\n    }\n"
        << "    ~" << adapter << "() override { if (!pl_onOwner()) std::terminate(); }\n"
        << "    int successOutcome() const { return pipelang::qt::InvocationOutcome::Success; }\n"
        << "    int cancelledOutcome() const { return pipelang::qt::InvocationOutcome::Cancelled; }\n"
        << "    int failureOutcome() const { return pipelang::qt::InvocationOutcome::Failure; }\n"
        << "    pipelang::qt::InvocationOutcome projectionStatus() const { pl_requireOwner(); return pl_projection_; }\n";
    for (const auto& property : model.properties)
        out << "    " << qtType(property.type) << " pl_get_" << property.name << "() const { pl_requireOwner(); return pl_value_" << property.name << "; }\n";
    for (const auto& action : model.actions) {
        out << "    Q_INVOKABLE pipelang::qt::ActionReport " << action.name << '(';
        for (std::size_t index = 0; index < action.parameters.size(); ++index) {
            if (index)
                out << ", ";
            out << qtType(action.parameters[index].type) << " pl_argument_" << index;
        }
        out << ") {\n        using Outcome = pipelang::qt::InvocationOutcome;\n"
            << "        if (!pl_onOwner()) return {Outcome::failure(QStringLiteral(\"qt.wrong_owner\")), Outcome::failure(QStringLiteral(\"qt.wrong_owner\"))};\n";
        if (!action.pure) {
            out << "        if (pl_invoking_) return {Outcome::failure(QStringLiteral(\"qt.reentry\")), pl_projection_};\n"
                << "        QScopedValueRollback<bool> pl_guard(pl_invoking_, true);\n";
        }
        out << "        try {\n";
        for (std::size_t index = 0; index < action.parameters.size(); ++index)
            out << "            auto pl_input_" << index << " = pipelang::qt::fromQt(pl_argument_" << index << ");\n";
        out << "            auto pl_result = pl_model_->" << action.name << '(';
        for (std::size_t index = 0; index < action.parameters.size(); ++index) {
            if (index)
                out << ", ";
            out << "std::move(pl_input_" << index << ')';
        }
        out << ");\n            auto pl_operation = pipelang::qt::outcome(pl_result);\n"
            << "            return {std::move(pl_operation), " << (action.pure ? "pl_projection_" : "pl_project()") << "};\n"
            << "        } catch (...) { return {Outcome::failure(QStringLiteral(\"qt.binding_failure\")), "
            << (action.pure ? "pl_projection_" : "pl_project()") << "}; }\n    }\n";
    }
    out << "Q_SIGNALS:\n    void projectionChanged();\nprivate:\n"
        << "    bool pl_onOwner() const { return QThread::currentThread() == pl_owner_ && thread() == pl_owner_; }\n"
        << "    void pl_requireOwner() const { if (!pl_onOwner()) throw pipelang::model::ExecutionFailure(\"qt.wrong_owner\"); }\n"
        << "    pipelang::qt::InvocationOutcome pl_project() {\n        try {\n            pl_requireOwner();\n"
        << "            [[maybe_unused]] const auto pl_snapshot = pl_model_->snapshot();\n";
    for (const auto& property : model.properties) {
        out << "            auto pl_next_" << property.name << " = pipelang::qt::toQt(";
        if (property.getter)
            out << "pl_model_->" << property.name << "()";
        else
            out << "pl_snapshot." << property.name;
        out << ");\n";
    }
    for (const auto& property : model.properties)
        out << "            pl_value_" << property.name << " = std::move(pl_next_" << property.name << ");\n";
    out << "            pl_projection_ = pipelang::qt::InvocationOutcome::success();\n"
        << "        } catch (...) { pl_projection_ = pipelang::qt::InvocationOutcome::failure(QStringLiteral(\"qt.projection_failed\")); }\n"
        << "        Q_EMIT projectionChanged();\n        return pl_projection_;\n    }\n"
        << "    std::unique_ptr<Model> pl_model_;\n    QThread* const pl_owner_;\n    bool pl_invoking_ = false;\n"
        << "    pipelang::qt::InvocationOutcome pl_projection_;\n";
    for (const auto& property : model.properties)
        out << "    " << qtType(property.type) << " pl_value_" << property.name << "{};\n";
    out << "};\n}\n";
    return out.str();
}
}
