#include "../../src/native/legacy-compiler/legacy.hpp"
#include <iostream>

namespace {
using namespace pipelang::legacy;
Json cases = Json::array();
void passed(const std::string& name) {
    cases.push_back({{"id", "materialize/" + name}, {"status", "passed"}});
}
template<class Action>
void refuses(const std::string& name, Action action) {
    bool refused = false;
    try {
        action();
    } catch (const std::exception&) {
        refused = true;
    }
    require(refused, "materializer expected refusal: " + name);
    passed(name);
}
void test(const fs::path& output, const fs::path& executable) {
    const auto project = output / "project";
    const auto root = project / "wf";
    const auto model = root / "models";
    const auto destination = project / "bin/.dockpipe/pipelang";
    atomicWrite(project / "dockpipe.config.json", R"({"schema":1,"compile":{"workflows":["wf","missing","wf"]}})");
    atomicWrite(root / "config.yml", "name: mapped\ntypes:\n  - models/IConfig\n");
    atomicWrite(model / "IConfig.pipe", "public Interface IConfig { public string IMAGE; }");
    atomicWrite(model / "AppConfig.pipe", "public Struct AppConfig : IConfig { public string IMAGE = \"nginx\"; }");
    const auto roots = workflowRoots(project);
    require(roots == std::vector<fs::path>{root, project / "missing", root}, "configured workflow roots differ");
    require(materialize(roots, false, destination) == 1, "mapped interface should emit once across duplicate roots");
    const auto artifact = destination / sha256(root.generic_string()).substr(0, 16) / "models/IConfig.AppConfig.workflow.yml";
    require(readFile(artifact, 65536) == "name: appconfig\ndescription: Generated by PipeLang v0.0.0.1\nvars:\n    IMAGE: nginx\n", "materializer mapping, path or artifact differs");
    require(!fs::exists(root / ".pipelang") && !fs::exists(model / ".pipelang"), "materializer wrote into sources");
    passed("configured-roots-mapped-interface");
    const auto stamp = fs::last_write_time(artifact);
    require(materialize(roots, false, destination) == 0 && fs::last_write_time(artifact) == stamp, "up-to-date materializer rewrote outputs");
    passed("up-to-date");
    require(materialize(roots, true, destination) == 1, "force did not emit mapped source");
    passed("force");
    fs::last_write_time(model / "AppConfig.pipe", fs::last_write_time(artifact) + std::chrono::seconds(2));
    require(materialize(roots, false, destination) == 1, "newer sibling source did not invalidate output");
    passed("sibling-invalidation");
    atomicWrite(root / "config.yml", "types: ['models/IConfig<IConfig>']\n");
    require(materialize(roots, true, destination) == 1, "flow-style explicit mapping failed");
    passed("flow-explicit-type");
    atomicWrite(root / "config.yml", "mapped: &selection 'models/IConfig<IConfig>'\ntypes: [*selection]\n");
    require(materialize(roots, true, destination) == 1, "YAML scalar alias mapping failed");
    passed("yaml-alias");
    const auto before = fileHash(artifact);
    for (const auto& [name, config] : std::map<std::string, std::string>{
            {"malformed-yaml", "types: [\n"}, {"duplicate-yaml-key", "types: []\ntypes: []\n"},
            {"mapping-type", "types: {}\n"}, {"mapping-member", "types: [{}]\n"},
            {"missing-bracket", "types: ['models/IConfig<']\n"},
            {"unknown-type", "types: ['models/IConfig<Unknown>']\n"}}) {
        atomicWrite(root / "config.yml", config);
        refuses(name, [&] { materialize(roots, true, destination); });
        require(fileHash(artifact) == before, "refused materialization changed existing output");
    }
    atomicWrite(root / "config.yml", "types: [models/IConfig]\n");
    atomicWrite(model / "Other.pipe", "Class Other : IConfig { string IMAGE; }");
    refuses("ambiguous-interface", [&] { materialize(roots, true, destination); });
    fs::remove(model / "Other.pipe");
    atomicWrite(root / "config.yml", "name: unmapped\n");
    require(materialize(roots, true, destination) == 1, "interface-only split units should not emit directly");
    passed("unmapped-class-discovery");
    atomicWrite(project / "dockpipe.config.json", R"({"compile":{"workflows":[]}})");
    require(workflowRoots(project).empty() && materialize({}, false, destination) == 0, "explicit empty roots should remain empty");
    passed("empty-roots");
    atomicWrite(project / "dockpipe.config.json", "{}");
    require(workflowRoots(project) == std::vector<fs::path>{project / "workflows"}, "default workflow root differs");
    passed("default-roots");
    atomicWrite(project / "dockpipe.config.json", R"({"compile":{"workflows":["wf"]}})");
    const auto result = process({executable.string(), "materialize", "--profile", "v0.0.0.1", "--workdir", project.string(), "--force"});
    require(result.exit == 0 && result.output.empty(), "installed native materializer failed: " + result.diagnostic);
    passed("installed-cli");
    require(process({executable.string(), "materialize", "--workdir", project.string()}).exit == 0, "materializer broke the active default CLI contract");
    passed("default-cli-contract");
    fs::create_symlink(model / "AppConfig.pipe", model / "alias.pipe");
    refuses("symbolic-source", [&] { materialize(roots, true, destination); });
    atomicWrite(output / "acceptance.json", canonical({{"status", "passed"}, {"cases", cases}, {"native_materializer", true}}));
}
}
int main(int argc, char** argv) {
    using namespace pipelang::tools;
    try {
        require(argc == 3, "materializer tests require fresh proof and installed CLI");
        const fs::path output = argv[1];
        require(output.is_absolute() && !fs::exists(output), "materializer proof must be fresh and absolute");
        fs::create_directories(output);
        test(output, argv[2]);
        std::cout << cases.size() << " native materializer cases passed\n";
        return 0;
    } catch (const std::exception& error) {
        std::cerr << "materializer oracle: " << error.what() << '\n';
        return 1;
    }
}
